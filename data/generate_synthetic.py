'''Write clearly-labeled SYNTHETIC data into data/synthetic/.

Reference implementation of a PROPOSAL. Everything written is made up: a toy Markov token stream, a
made-up need matrix, and a made-up roofline-style cost table. Nothing is a real dataset or a
hardware measurement.

Usage (from the repo root):  python data/generate_synthetic.py [--seed 0]
'''
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.cost_tables import make_synthetic_cost_table  # noqa: E402
from src.synthetic_tasks import LABEL, make_markov_tokens, make_need_matrix  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--seed', type=int, default=0)
    ap.add_argument('--layers', type=int, default=8)
    ap.add_argument('--vocab', type=int, default=8)
    ap.add_argument('--n-tokens', type=int, default=4000)
    args = ap.parse_args()

    out = ROOT / 'data' / 'synthetic'
    out.mkdir(parents=True, exist_ok=True)
    tokens = make_markov_tokens(args.n_tokens, args.vocab, args.seed)
    need = make_need_matrix(args.vocab, args.layers, args.seed)
    table = make_synthetic_cost_table(args.layers, args.seed)

    (out / 'tokens.json').write_text(json.dumps({'synthetic': True, 'label': LABEL, 'tokens': tokens}))
    (out / 'need_matrix.json').write_text(json.dumps({'synthetic': True, 'label': LABEL, 'need': need}))
    (out / 'cost_table.json').write_text(json.dumps(table.to_dict(), indent=2))
    (out / 'README_SYNTHETIC.txt').write_text(
        'ALL FILES IN THIS DIRECTORY ARE SYNTHETIC.\n'
        'They are generated by data/generate_synthetic.py from a seed.\n'
        'They are not real datasets and not hardware measurements.\n')
    print('Wrote SYNTHETIC data to', out)


if __name__ == '__main__':
    main()
